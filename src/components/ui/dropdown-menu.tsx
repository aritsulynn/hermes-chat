// Dropdown menu, on Base UI's Menu. The sidebar's account menu is the first
// caller; this is the Base UI counterpart of the Radix `dropdown-menu` shadcn
// used to ship, and it is here rather than in the Radix set because the sidebar
// is on Base UI (see sidebar.tsx for why that split exists).
//
// The two libraries have different prop shapes, and one of them bites when porting
// call sites: Radix composes with `asChild`, Base UI composes with `render`.
//
//   Radix:  <DropdownMenuTrigger asChild><Button /></DropdownMenuTrigger>
//   Base UI: <DropdownMenuTrigger render={<Button />}>
//
// One subclass of side effect is worth knowing when editing the class strings
// below: Base UI names its animation states `data-open` / `data-closed` and the
// trigger's open state `data-popup-open`, where Radix said `data-[state=open]`.
// shadcn's Radix version of this file used the Radix spelling.
import * as React from 'react';
import { Menu as MenuPrimitive } from '@base-ui/react/menu';
import { Check, ChevronRight } from 'lucide-react';
import { cn } from '@/utils/cn';

function DropdownMenu({ ...props }: MenuPrimitive.Root.Props) {
  return <MenuPrimitive.Root data-slot="dropdown-menu" {...props} />;
}

/**
 * A handle for a menu whose trigger lives somewhere else in the tree.
 *
 * Normal menus keep the trigger inside the root:
 *
 *   <DropdownMenu>
 *     <DropdownMenuTrigger render={<Button />}>…</DropdownMenuTrigger>
 *     <DropdownMenuContent>…</DropdownMenuContent>
 *   </DropdownMenu>
 *
 * The composer cannot do that. Its buttons sit in the composer, but the menu
 * bodies belong to the chat screen — that split is old (Android drops touches
 * outside a parent's bounds) and is no longer needed now that the popup portals
 * to `body`, but the *data* the bodies read still lives on the screen. A handle
 * lets the two halves stay where they are:
 *
 *   // in the composer
 *   <DropdownMenuTrigger handle={h} id="attach" render={<Button />} />
 *   // in the chat screen
 *   <DropdownMenu handle={h}>…</DropdownMenu>
 *
 * Base UI then anchors the popup to whichever trigger opened it. `open(triggerId)`
 * on the handle is the imperative form if a call site needs to open one from a
 * handler rather than from the trigger's own click.
 */
const createDropdownMenuHandle = MenuPrimitive.createHandle;

export type DropdownMenuHandle = ReturnType<typeof createDropdownMenuHandle>;

function DropdownMenuPortal({ ...props }: MenuPrimitive.Portal.Props) {
  return <MenuPrimitive.Portal data-slot="dropdown-menu-portal" {...props} />;
}

function DropdownMenuTrigger({ ...props }: MenuPrimitive.Trigger.Props) {
  return <MenuPrimitive.Trigger data-slot="dropdown-menu-trigger" {...props} />;
}

